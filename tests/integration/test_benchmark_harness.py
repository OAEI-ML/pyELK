from __future__ import annotations

import hashlib
import json
import os
import subprocess
import sys
from pathlib import Path

import pytest
from benchmarks import bench_biomedical

ROOT = Path(__file__).resolve().parents[2]
MANIFEST = ROOT / "benchmarks" / "manifest.toml"


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _biomedical_fixture(tmp_path: Path) -> dict[str, object]:
    source = tmp_path / "source.ofn"
    source.write_text(
        """Prefix(:=<https://example.org/source#>)
Ontology(<https://example.org/source>
 Declaration(Class(:A))
 Declaration(Class(:B))
 SubClassOf(:A :B)
)
""",
        encoding="utf-8",
    )
    target = tmp_path / "target.ofn"
    target.write_text(
        """Prefix(:=<https://example.org/target#>)
Ontology(<https://example.org/target>
 Declaration(Class(:C))
 Declaration(Class(:D))
 SubClassOf(:C :D)
)
""",
        encoding="utf-8",
    )
    alignment = tmp_path / "train.tsv"
    alignment.write_text(
        "SrcEntity\tTgtEntity\nhttps://example.org/source#A\thttps://example.org/target#C\n",
        encoding="utf-8",
    )
    return {
        "source_path": source,
        "source_sha256": _sha256(source),
        "source_axiom_count": 3,
        "source_entity_count": 2,
        "target_path": target,
        "target_sha256": _sha256(target),
        "target_axiom_count": 3,
        "target_entity_count": 2,
        "alignment_path": alignment,
        "alignment_sha256": _sha256(alignment),
        "corpus_name": "tiny-biomedical-fixture",
        "corpus_source": "generated by the test suite",
        "corpus_license": "Apache-2.0",
        "backends": ("python",),
        "workers": 1,
        "warmups": 0,
        "repeats": 1,
    }


def test_performance_manifest_pins_every_required_corpus_and_threshold() -> None:
    text = MANIFEST.read_text(encoding="utf-8")
    assert text.startswith('schema = "pyelk.performance-corpus/1"')
    assert text.count("[[corpora]]") == 6
    for value in (
        "elk-0.6.0-frozen",
        "generated-el-chain-medium",
        "generated-el-chain-large",
        "generated-property-chain-large",
        "generated-taxonomy-mixed",
        "shared-snapshot-million",
        "native_python_geometric_mean_speedup = 5.0",
        "native_boundary_fraction_max = 0.05",
        "release_regression_fraction_max = 0.10",
        'runner = "benchmarks/bench_biomedical.py"',
        'verification = "all three hashes are checked before either ontology is parsed"',
        'closure_policy = "source and target must be self-contained',
        (
            'alignment_semantics = "TSV SrcEntity/TgtEntity rows become '
            'EquivalentClasses bridge axioms"'
        ),
    ):
        assert value in text
    assert (
        hashlib.sha256(
            (ROOT / "tests" / "data" / "elk-v0.6.0" / "manifest.json").read_bytes()
        ).hexdigest()
        in text
    )


def test_quick_integrated_benchmark_is_java_free_and_semantic_checking(
    tmp_path: Path,
) -> None:
    biomedical = _biomedical_fixture(tmp_path)
    environment = os.environ.copy()
    environment["PATH"] = ""
    completed = subprocess.run(
        [
            sys.executable,
            str(ROOT / "tools" / "benchmark.py"),
            "--suite",
            "quick",
            "--workers",
            "1",
            "--biomedical-source",
            str(biomedical["source_path"]),
            "--biomedical-source-sha256",
            str(biomedical["source_sha256"]),
            "--biomedical-source-axiom-count",
            str(biomedical["source_axiom_count"]),
            "--biomedical-source-entity-count",
            str(biomedical["source_entity_count"]),
            "--biomedical-target",
            str(biomedical["target_path"]),
            "--biomedical-target-sha256",
            str(biomedical["target_sha256"]),
            "--biomedical-target-axiom-count",
            str(biomedical["target_axiom_count"]),
            "--biomedical-target-entity-count",
            str(biomedical["target_entity_count"]),
            "--biomedical-alignment",
            str(biomedical["alignment_path"]),
            "--biomedical-alignment-sha256",
            str(biomedical["alignment_sha256"]),
            "--biomedical-name",
            str(biomedical["corpus_name"]),
            "--biomedical-origin",
            str(biomedical["corpus_source"]),
            "--biomedical-license",
            str(biomedical["corpus_license"]),
        ],
        cwd=ROOT,
        env=environment,
        check=False,
        capture_output=True,
        text=True,
    )
    assert completed.returncode == 0, completed.stderr
    payload = json.loads(completed.stdout)
    assert payload["schema"] == "pyelk.integrated-benchmark/1"
    assert payload["native"] is False
    assert payload["java_comparison"] is None
    assert set(payload["results"]) == {
        "biomedical",
        "class-saturation",
        "end-to-end",
        "property-saturation",
        "snapshot-ingestion",
        "taxonomy",
    }
    assert payload["results"]["end-to-end"]["backend"] == "python"
    assert payload["results"]["end-to-end"]["result_sha256"]
    assert payload["results"]["biomedical"]["backend_parity"] == {
        "source": True,
        "target": True,
        "composite": True,
    }


def test_biomedical_hash_mismatch_fails_before_any_parse(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    arguments = _biomedical_fixture(tmp_path)
    arguments["alignment_sha256"] = "0" * 64
    calls = 0

    def unexpected_load(*args: object, **kwargs: object) -> object:
        nonlocal calls
        calls += 1
        raise AssertionError("hash verification must finish before parsing")

    monkeypatch.setattr(bench_biomedical.owl, "load_snapshot", unexpected_load)
    with pytest.raises(ValueError, match="alignment SHA-256 mismatch"):
        bench_biomedical.run(**arguments)
    assert calls == 0


def test_biomedical_runner_loads_each_ontology_once_and_preserves_views(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    arguments = _biomedical_fixture(tmp_path)
    original = bench_biomedical.owl.load_snapshot
    loaded: list[Path] = []

    def counting_load(path: Path, **kwargs: object) -> object:
        loaded.append(Path(path).resolve())
        return original(path, **kwargs)

    monkeypatch.setattr(bench_biomedical.owl, "load_snapshot", counting_load)
    payload = bench_biomedical.run(**arguments)

    assert loaded == [arguments["source_path"], arguments["target_path"]]
    assert payload["schema"] == "pyelk.biomedical-benchmark/1"
    assert payload["gate_eligible"] is False
    assert payload["protocol"]["allocation_tracing"] is False
    assert payload["load_and_compose"]["load_calls"] == {"source": 1, "target": 1}
    assert payload["load_and_compose"]["composite_members_retained_by_identity"] is True
    assert payload["load_and_compose"]["serialized_intermediate_created"] is False
    assert payload["backend_parity"] == {
        "source": True,
        "target": True,
        "composite": True,
    }
    python_views = payload["backends"]["python"]["views"]
    for row in python_views.values():
        assert row["identity_preserved"] is True
        assert row["provider_calls"] == row["provider_calls_expected"] == 1
        assert len(row["semantic_completeness_sha256"]) == 64
        assert row["session_construction"]["samples"][0]["peak_traced_bytes"] is None


def test_biomedical_python_rust_semantic_parity_when_workspace_native_exists(
    tmp_path: Path,
) -> None:
    candidates = (
        ROOT / "target" / "release" / "lib_native.dylib",
        ROOT / "target" / "release" / "lib_native.so",
        ROOT / "target" / "debug" / "lib_native.dylib",
        ROOT / "target" / "debug" / "lib_native.so",
    )
    native_path = next((path for path in candidates if path.is_file()), None)
    if native_path is None:
        pytest.skip("workspace native extension is not built")
    arguments = _biomedical_fixture(tmp_path)
    arguments["backends"] = ("python", "rust")
    arguments["native_path"] = native_path

    payload = bench_biomedical.run(**arguments)

    assert payload["backend_parity"] == {
        "source": True,
        "target": True,
        "composite": True,
    }
    assert payload["backends"]["rust"]["backend"]["name"] == "rust"
    assert payload["backends"]["rust"]["native_transfer"]["observable"] is False
