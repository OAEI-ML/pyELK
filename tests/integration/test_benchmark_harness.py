def test_advertised_core_ingestion_uses_only_the_public_producer() -> None:
    from pyowl_core.backends import native as core_native

    candidates = (
        ROOT / "target" / "release" / "lib_native.dylib",
        ROOT / "target" / "release" / "lib_native.so",
        ROOT / "target" / "debug" / "lib_native.dylib",
        ROOT / "target" / "debug" / "lib_native.so",
    )
    native_path = next((path for path in candidates if path.is_file()), None)
    if native_path is None:
        pytest.skip("workspace native extension is not built")
    if not core_native.probe(refresh=True).available:
        pytest.skip("installed pyowl-core native extension is unavailable")
    probe = bench_encoded_ingestion._workloads(4)["direct"]
    if (
        probe.capabilities.encoded_view_schemas.get(bench_encoded_ingestion.ENCODED_SCHEMA_NAME)
        != bench_encoded_ingestion.ENCODED_SCHEMA_VERSION
    ):
        pytest.skip("installed pyowl-core does not advertise structural-columns v2")

    payload = bench_encoded_ingestion.run(
        class_count=20,
        repeats=1,
        warmups=0,
        warm_queries=2,
        workers=1,
        native_path=native_path,
        experimental_producer=False,
        enforce=False,
    )

    assert payload["gate_eligible"] is False
    capabilities = payload["capabilities"]
    assert capabilities["producer_modes"] == ["public-negotiated-retained"]
    assert set(capabilities["core_advertised_schemas"].values()) == {
        bench_encoded_ingestion.ENCODED_SCHEMA_VERSION
    }
    assert (
        capabilities["native_advertised_schema"] == bench_encoded_ingestion.ENCODED_SCHEMA_VERSION
    )
    assert (
        "native extension does not advertise structural-columns v2" not in payload["gate_blockers"]
    )
    for row in payload["workloads"].values():
        counters = row["encoded_native"]["counters"]
        assert counters["scalar_axiom_materializations"] == 0
        assert counters["base_flattening_bytes"] == 0
        assert counters["wire_encoder_calls"] == 0
        assert counters["wire_decoder_calls"] == 0
    direct = payload["workloads"]["direct"]["encoded_native"]
    mapped = payload["workloads"]["mmap"]["encoded_native"]
    overlay = payload["workloads"]["overlay"]["encoded_native"]
    composite = payload["workloads"]["composite"]["encoded_native"]
    assert direct["counters"]["staging_copy_bytes"] == 0
    assert mapped["counters"]["staging_copy_bytes"] == 0
    assert mapped["diagnostics"]["encoded_detached_buffer_count"] == 0
    assert mapped["diagnostics"]["encoded_indexed_buffer_count"] == 11
    assert mapped["diagnostics"]["encoded_compiler_gil_released"] is False
    assert overlay["counters"]["staging_copy_bytes"] == 0
    assert composite["counters"]["staging_copy_bytes"] == 4
    assert composite["diagnostics"]["encoded_posting_bytes"] == 4


