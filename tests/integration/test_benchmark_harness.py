def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _biomedical_fixture(tmp_path: Path) -> dict[str, object]:
    source = tmp_path / "source.ofn"
    source.write_text(
        """Prefix(:=<https://example.org/source#>)
Ontology(<https://example.org/source>
 Declaration(Class(:A))
 Declaration(Class(:B))
 SubClassOf(:A :B)
)
""",
        encoding="utf-8",
    )
    target = tmp_path / "target.ofn"
    target.write_text(
        """Prefix(:=<https://example.org/target#>)
Ontology(<https://example.org/target>
 Declaration(Class(:C))
 Declaration(Class(:D))
 SubClassOf(:C :D)
)
""",
        encoding="utf-8",
    )
    alignment = tmp_path / "train.tsv"
    alignment.write_text(
        "SrcEntity\tTgtEntity\nhttps://example.org/source#A\thttps://example.org/target#C\n",
        encoding="utf-8",
    )
    return {
        "source_path": source,
        "source_sha256": _sha256(source),
        "source_axiom_count": 3,
        "source_entity_count": 2,
        "target_path": target,
        "target_sha256": _sha256(target),
        "target_axiom_count": 3,
        "target_entity_count": 2,
        "alignment_path": alignment,
        "alignment_sha256": _sha256(alignment),
        "corpus_name": "tiny-biomedical-fixture",
        "corpus_source": "generated by the test suite",
        "corpus_license": "Apache-2.0",
        "backends": ("python",),
        "workers": 1,
        "warmups": 0,
        "repeats": 1,
    }


def _semantic_expectations(payload: dict[str, object]) -> dict[str, str]:
    backends = payload["backends"]
    assert isinstance(backends, dict)
    python = backends["python"]
    assert isinstance(python, dict)
    views = python["views"]
    assert isinstance(views, dict)
    return {
        f"expected_{name}_semantic_completeness_sha256": str(
            views[name]["semantic_completeness_sha256"]
        )
        for name in ("source", "target", "composite")
    }


