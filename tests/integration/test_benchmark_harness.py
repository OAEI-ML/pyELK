def test_quick_integrated_benchmark_is_java_free_and_semantic_checking(
    tmp_path: Path,
) -> None:
    biomedical = _biomedical_fixture(tmp_path)
    environment = os.environ.copy()
    environment["PATH"] = ""
    completed = subprocess.run(
        [
            sys.executable,
            str(ROOT / "tools" / "benchmark.py"),
            "--suite",
            "quick",
            "--workers",
            "1",
            "--biomedical-source",
            str(biomedical["source_path"]),
            "--biomedical-source-sha256",
            str(biomedical["source_sha256"]),
            "--biomedical-source-axiom-count",
            str(biomedical["source_axiom_count"]),
            "--biomedical-source-entity-count",
            str(biomedical["source_entity_count"]),
            "--biomedical-target",
            str(biomedical["target_path"]),
            "--biomedical-target-sha256",
            str(biomedical["target_sha256"]),
            "--biomedical-target-axiom-count",
            str(biomedical["target_axiom_count"]),
            "--biomedical-target-entity-count",
            str(biomedical["target_entity_count"]),
            "--biomedical-alignment",
            str(biomedical["alignment_path"]),
            "--biomedical-alignment-sha256",
            str(biomedical["alignment_sha256"]),
            "--biomedical-name",
            str(biomedical["corpus_name"]),
            "--biomedical-origin",
            str(biomedical["corpus_source"]),
            "--biomedical-license",
            str(biomedical["corpus_license"]),
        ],
        cwd=ROOT,
        env=environment,
        check=False,
        capture_output=True,
        text=True,
    )
    assert completed.returncode == 0, completed.stderr
    payload = json.loads(completed.stdout)
    assert payload["schema"] == "pyelk.integrated-benchmark/1"
    assert payload["native"] is False
    assert payload["java_comparison"] is None
    assert set(payload["results"]) == {
        "biomedical",
        "class-saturation",
        "end-to-end",
        "property-saturation",
        "snapshot-ingestion",
        "taxonomy",
    }
    assert payload["results"]["end-to-end"]["backend"] == "python"
    assert payload["results"]["end-to-end"]["result_sha256"]
    assert payload["results"]["biomedical"]["backend_parity"] == {
        "source": True,
        "target": True,
        "composite": True,
    }


def test_biomedical_hash_mismatch_fails_before_any_parse(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    arguments = _biomedical_fixture(tmp_path)
    arguments["alignment_sha256"] = "0" * 64
    calls = 0

    def unexpected_load(*args: object, **kwargs: object) -> object:
        nonlocal calls
        calls += 1
        raise AssertionError("hash verification must finish before parsing")

    monkeypatch.setattr(bench_biomedical.owl, "load_snapshot", unexpected_load)
    with pytest.raises(ValueError, match="alignment SHA-256 mismatch"):
        bench_biomedical.run(**arguments)
    assert calls == 0


def test_biomedical_runner_loads_each_ontology_once_and_preserves_views(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    arguments = _biomedical_fixture(tmp_path)
    original = bench_biomedical.owl.load_snapshot
    loaded: list[tuple[str, str]] = []

    def counting_load(source: object, **kwargs: object) -> object:
        assert isinstance(source, bytes)
        document_iri = kwargs.get("document_iri")
        assert isinstance(document_iri, str)
        loaded.append((hashlib.sha256(source).hexdigest(), document_iri))
        return original(source, **kwargs)

    monkeypatch.setattr(bench_biomedical.owl, "load_snapshot", counting_load)
    payload = bench_biomedical.run(**arguments)

    source_path = arguments["source_path"]
    target_path = arguments["target_path"]
    assert isinstance(source_path, Path)
    assert isinstance(target_path, Path)
    assert loaded == [
        (arguments["source_sha256"], source_path.resolve().as_uri()),
        (arguments["target_sha256"], target_path.resolve().as_uri()),
    ]
    assert payload["schema"] == "pyelk.biomedical-benchmark/2"
    assert payload["gate_eligible"] is False
    assert payload["protocol"]["allocation_tracing"] is False
    assert payload["load_and_compose"]["load_calls"] == {"source": 1, "target": 1}
    assert payload["load_and_compose"]["composite_members_retained_by_identity"] is True
    assert payload["load_and_compose"]["serialized_intermediate_created"] is False
    assert payload["backend_parity"] == {
        "source": True,
        "target": True,
        "composite": True,
    }
    python_views = payload["backends"]["python"]["views"]
    for row in python_views.values():
        assert row["identity_preserved"] is True
        assert row["provider_calls"] == row["provider_calls_expected"] == 1
        assert len(row["semantic_completeness_sha256"]) == 64
        sample = row["session_construction"]["samples"][0]
        assert sample["peak_traced_bytes"] is None
        assert "process_peak_rss_high_water_growth_bytes" in sample
        assert "process_peak_rss_increase_bytes" not in sample
    assert "process-lifetime ru_maxrss high-water marks" in payload["protocol"]["rss_observation"]


def test_biomedical_rechecks_captured_bytes_before_parsing(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    arguments = _biomedical_fixture(tmp_path)
    source_path = arguments["source_path"]
    assert isinstance(source_path, Path)
    original = bench_biomedical._read_verified_bytes

    def mutate_before_capture(path: Path, expected_sha256: str, label: str) -> bytes:
        if label == "source ontology":
            path.write_bytes(path.read_bytes() + b"\n")
        return original(path, expected_sha256, label)

    monkeypatch.setattr(bench_biomedical, "_read_verified_bytes", mutate_before_capture)
    with pytest.raises(ValueError, match="source ontology changed after initial verification"):
        bench_biomedical.run(**arguments)


@pytest.mark.parametrize(
    ("row", "message"),
    (
        (
            "https://example.org/source#Missing\thttps://example.org/target#C\n",
            "SrcEntity .* is not a named class in the source ontology",
        ),
        (
            "https://example.org/source#A\thttps://example.org/target#Missing\n",
            "TgtEntity .* is not a named class in the target ontology",
        ),
        (
            "https://example.org/target#C\thttps://example.org/source#A\n",
            "SrcEntity .* is not a named class in the source ontology",
        ),
    ),
)
def test_biomedical_alignment_must_reference_classes_in_the_declared_direction(
    tmp_path: Path,
    row: str,
    message: str,
) -> None:
    arguments = _biomedical_fixture(tmp_path)
    alignment = arguments["alignment_path"]
    assert isinstance(alignment, Path)
    alignment.write_text("SrcEntity\tTgtEntity\n" + row, encoding="utf-8")
    arguments["alignment_sha256"] = _sha256(alignment)

    with pytest.raises(ValueError, match=message):
        bench_biomedical.run(**arguments)


def test_biomedical_semantic_expectations_are_pinned_and_fail_closed(tmp_path: Path) -> None:
    arguments = _biomedical_fixture(tmp_path)
    baseline = bench_biomedical.run(**arguments)
    expectations = _semantic_expectations(baseline)

    verified = bench_biomedical.run(**arguments, **expectations)
    assert verified["semantic_expectations"] == {
        "provided": True,
        "digests": {
            name: expectations[f"expected_{name}_semantic_completeness_sha256"]
            for name in ("source", "target", "composite")
        },
        "matched": {"source": True, "target": True, "composite": True},
    }

    wrong = dict(expectations)
    wrong["expected_composite_semantic_completeness_sha256"] = "0" * 64
    with pytest.raises(AssertionError, match="composite semantic/completeness digest mismatch"):
        bench_biomedical.run(**arguments, **wrong)


def test_integrated_enforcement_requires_digests_and_rejects_ineligible_evidence(
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    arguments = _biomedical_fixture(tmp_path)
    inputs = integrated_benchmark.BiomedicalInputs(
        source=arguments["source_path"],
        source_sha256=arguments["source_sha256"],
        source_axiom_count=arguments["source_axiom_count"],
        source_entity_count=arguments["source_entity_count"],
        target=arguments["target_path"],
        target_sha256=arguments["target_sha256"],
        target_axiom_count=arguments["target_axiom_count"],
        target_entity_count=arguments["target_entity_count"],
        alignment=arguments["alignment_path"],
        alignment_sha256=arguments["alignment_sha256"],
        name=arguments["corpus_name"],
        origin=arguments["corpus_source"],
        license=arguments["corpus_license"],
    )
    with pytest.raises(ValueError, match="caller-pinned biomedical semantic digests"):
        integrated_benchmark.run(
            suite="full",
            native=True,
            workers=1,
            enforce=True,
            java_report=None,
            machine_label="test-runner",
            native_path=None,
            biomedical=inputs,
        )

    pinned = integrated_benchmark.BiomedicalInputs(
        **{
            field: getattr(inputs, field)
            for field in (
                "source",
                "source_sha256",
                "source_axiom_count",
                "source_entity_count",
                "target",
                "target_sha256",
                "target_axiom_count",
                "target_entity_count",
                "alignment",
                "alignment_sha256",
                "name",
                "origin",
                "license",
            )
        },
        expected_source_semantic_completeness_sha256="1" * 64,
        expected_target_semantic_completeness_sha256="2" * 64,
        expected_composite_semantic_completeness_sha256="3" * 64,
    )
    command_arguments = pinned.command_arguments()
    for flag in (
        "--expected-source-semantic-completeness-sha256",
        "--expected-target-semantic-completeness-sha256",
        "--expected-composite-semantic-completeness-sha256",
    ):
        assert flag in command_arguments
    monkeypatch.setattr(
        integrated_benchmark,
        "_suite",
        lambda *args, **kwargs: [("biomedical", ["biomedical"])],
    )
    monkeypatch.setattr(
        integrated_benchmark,
        "_run",
        lambda *args, **kwargs: {"gate_eligible": False, "gate_blockers": ["review pending"]},
    )
    with pytest.raises(RuntimeError, match="biomedical benchmark evidence is not gate-eligible"):
        integrated_benchmark.run(
            suite="full",
            native=True,
            workers=1,
            enforce=True,
            java_report=None,
            machine_label="test-runner",
            native_path=None,
            biomedical=pinned,
        )


def test_biomedical_python_rust_semantic_parity_when_workspace_native_exists(
    tmp_path: Path,
) -> None:
    candidates = (
        ROOT / "target" / "release" / "lib_native.dylib",
        ROOT / "target" / "release" / "lib_native.so",
        ROOT / "target" / "debug" / "lib_native.dylib",
        ROOT / "target" / "debug" / "lib_native.so",
    )
    native_path = next((path for path in candidates if path.is_file()), None)
    if native_path is None:
        pytest.skip("workspace native extension is not built")
    arguments = _biomedical_fixture(tmp_path)
    arguments["backends"] = ("python", "rust")
    arguments["native_path"] = native_path

    payload = bench_biomedical.run(**arguments)

    assert payload["backend_parity"] == {
        "source": True,
        "target": True,
        "composite": True,
    }
    assert payload["backends"]["rust"]["backend"]["name"] == "rust"
    transfer = payload["backends"]["rust"]["native_transfer"]
    assert transfer["observable"] is True
    assert {row["ingestion_path"] for row in transfer["views"].values()} <= {
        "scalar-wire",
        "encoded-native",
    }


def test_encoded_ingestion_smoke_is_exact_and_explicitly_non_gating() -> None:
    candidates = (
        ROOT / "target" / "release" / "lib_native.dylib",
        ROOT / "target" / "release" / "lib_native.so",
        ROOT / "target" / "debug" / "lib_native.dylib",
        ROOT / "target" / "debug" / "lib_native.so",
    )
    native_path = next((path for path in candidates if path.is_file()), None)
    if native_path is None:
        pytest.skip("workspace native extension is not built")

    payload = bench_encoded_ingestion.run(
        class_count=20,
        repeats=1,
        warmups=0,
        warm_queries=2,
        workers=1,
        native_path=native_path,
        experimental_producer=True,
        enforce=False,
    )

    assert payload["schema"] == "pyelk.encoded-ingestion-benchmark/1"
    assert payload["fixture"]["hierarchy_component_classes"] == 8
    assert payload["gate_eligible"] is False
    assert payload["capabilities"]["producer_modes"] == ["experimental-scalar-fallback"]
    assert set(payload["workloads"]) == {"direct", "overlay", "composite"}
    for name, row in payload["workloads"].items():
        assert row["parity"] == {
            "compiler_digest": True,
            "compiler_counts": True,
            "packed_first_result": True,
        }
        counters = row["encoded_native"]["counters"]
        assert counters["serialized_private_ir_bytes"] == 0
        assert counters["staging_copy_bytes"] == 0
        assert counters["wire_encoder_calls"] == 0
        assert counters["wire_decoder_calls"] == 0
        assert counters["scalar_axiom_materializations"] > 0
        assert row["encoded_native"]["diagnostics"]["encoded_compiler_gil_released"] is True
        assert row["encoded_native"]["phases"]["view_to_first_result"]["samples"]
        if name == "direct":
            assert counters["base_flattening_bytes"] == 0
        else:
            assert counters["base_flattening_bytes"] > 0


